export function parseLevel(level) {
  const walls = new Set();
  const crates = new Set();
  const coins = [];
  const ledgers = [];
  let playerStart = { x: 1, y: 1 };
  let exit = { x: 28, y: 17 };
  level.map.forEach((row, y) => {
    [...row].forEach((ch, x) => {
      const key = x + ',' + y;
      if (ch === '#') walls.add(key);
      else if (ch === 'C') crates.add(key);
      else if (ch === 'P') playerStart = { x, y };
      else if (ch === 'E') exit = { x, y };
      else if (ch === 'L') ledgers.push({ x, y, taken: false });
      else if (ch === 'o') coins.push({ x, y, taken: false });
    });
  });
  return { walls, crates, coins, ledgers, playerStart, exit };
}
